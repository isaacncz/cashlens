import assert from 'node:assert/strict';

export async function checkCompoundFlow(page, width) {
  const chapter = name => page.getByRole('navigation', { name: 'Consultation chapters' }).getByRole('button', { name, exact: true });
  const sheet = page.getByRole('dialog', { name: /^Edit / });
  const edit = async id => { await page.locator(`.rs-story-product[data-product-id="${id}"] button`).click(); await sheet.waitFor(); return sheet; };
  const done = () => sheet.getByRole('button', { name: 'Done', exact: true }).click();
  const reset = async () => { await page.getByRole('button', { name: 'More options', exact: true }).click(); await page.getByRole('menuitem', { name: 'Reset example', exact: true }).click(); };
  const period = name => page.getByRole('radio', { name, exact: true });
  const customMonths = async value => { await page.getByRole('radio', { name: 'Custom', exact: true }).check(); await page.locator('#rs-months').fill(String(value)); };
  await reset();
  assert.equal(await page.locator('.rs-story-amount').innerText(), 'RM 118.00');
  assert.equal(await page.locator('.rs-story-product').count(), 1);
  await page.locator('.rs-story-product img').evaluate(image => image.decode());
  if (width < 1200) {
    const dock = page.locator('.rs-mobile-summary');
    assert.ok(await dock.evaluate(element => element.scrollWidth <= element.clientWidth + 1), 'Dock contents fit');
    const box = await dock.boundingBox(), main = await page.locator('#main-content').boundingBox();
    assert.ok(main.y + main.height <= box.y + 1, 'The action dock never covers the story');
  }
  for (const button of await page.locator('.rs-chapters button, .rs-product-row, .rs-more > button').all()) assert.ok((await button.boundingBox()).height >= 44);
  await edit('124106');
  assert.equal(await sheet.getByRole('button', { name: /Remove product/ }).count(), 0, 'The starting product stays in the story');
  await sheet.getByRole('combobox', { name: 'Purchase interval for Glister Multi-Action Toothpaste, 200g', exact: true }).selectOption('1');
  assert.equal(await page.locator('.rs-story-amount').innerText(), 'RM 354.00');
  await sheet.getByRole('combobox', { name: 'Purchase interval for Glister Multi-Action Toothpaste, 200g', exact: true }).selectOption('3');
  await done();
  await page.getByRole('button', { name: 'Choose a different starting product', exact: true }).click();
  const picker = page.getByRole('dialog', { name: 'Choose a product', exact: true });
  await picker.getByRole('searchbox').fill('50g');
  await picker.getByRole('radio', { name: 'Select Glister Multi-Action Toothpaste, 50g', exact: true }).check();
  await picker.getByRole('button', { name: 'Done', exact: true }).click();
  assert.equal(await page.locator('.rs-story-amount').innerText(), 'RM 57.00');
  await reset();
  await chapter('Year 2').click();
  assert.equal(await page.locator('.rs-story-product').count(), 3, 'Year 2 retains toothpaste and adds two products');
  assert.equal(await page.locator('.rs-new-label').count(), 2);
  assert.equal(await page.locator('.rs-story-amount').innerText(), 'RM 594.00', 'The chapter emphasizes annual, not cumulative, revenue');
  await page.getByRole('button', { name: 'Choose products for year 2', exact: true }).click();
  const additions = page.getByRole('dialog', { name: 'Choose products', exact: true });
  assert.ok(await additions.getByRole('checkbox', { name: 'Select Glister Multi-Action Toothpaste, 200g', exact: true }).isDisabled(), 'Earlier products carry forward in the guided story');
  await additions.getByRole('searchbox').fill('no-such-product');
  assert.ok(await additions.getByText('No matching products.', { exact: true }).isVisible());
  await additions.getByRole('button', { name: 'Clear filters', exact: true }).click();
  await additions.getByRole('checkbox', { name: 'Select Glister Multi-Action Dental Floss, 2/pack', exact: true }).check();
  await additions.getByRole('button', { name: 'Done', exact: true }).click();
  assert.equal(await page.locator('.rs-story-product').count(), 4);
  await reset();
  await chapter('Year 3').click();
  assert.equal(await page.locator('.rs-story-product').count(), 4);
  assert.equal(await page.locator('.rs-new-label').count(), 1);
  assert.equal(await page.locator('.rs-story-amount').innerText(), 'RM 2,142');
  const growthStory = page.getByRole('switch', { name: /Now add one new customer a year/ });
  await growthStory.uncheck();
  assert.equal(await page.locator('.rs-story-amount').innerText(), 'RM 714.00', 'Basket and customer growth are independently visible');
  await growthStory.check();
  assert.deepEqual(await page.locator('.rs-story-receipt [data-state=reached]').evaluateAll(bars => bars.map(bar => bar.dataset.year)), ['1', '2', '3'], 'Year 3 lights three yearly bars');
  assert.equal(await page.locator('.rs-story-receipt [data-state=later]').count(), 2, 'Later years stay faint');
  assert.equal(await page.locator('.rs-story-delta').innerText(), '+RM 954.00 vs year 2 · 1.8×');
  if (width < 768) assert.ok((await page.locator('.rs-story-receipt').boundingBox()).y < (await page.locator('.rs-story-product').first().boundingBox()).y, 'The result comes before the basket on phones');
  await chapter('My plan').click();
  assert.equal(await page.getByRole('group', { name: 'Consultation view' }).count(), 0, 'Inputs and results share one view');
  assert.equal(await page.locator('.rs-result [data-year]').count(), 20, 'My plan shows one bar per year');
  assert.ok(await period('20 years').isChecked());
  assert.equal(await page.locator('#rs-customers-per-year').inputValue(), '1');
  assert.match(await page.locator('#rs-growth-help').innerText(), /reach 20 customers in year 20/);
  assert.equal(await page.locator('.rs-revenue').innerText(), 'RM 149,104', 'Totals from RM 1,000 show whole ringgit');
  assert.equal(await page.locator('.rs-insight').innerText(), 'From year 3, your starting customer’s basket holds at RM 714 a year. After that, new customers add about RM 714 more each year. Growth stops at the 20-customer cap in year 20.');
  await customMonths(36);
  assert.equal(await page.locator('.rs-revenue').innerText(), 'RM 3,448');
  await customMonths(48);
  assert.deepEqual(await page.locator('.rs-plan-year').evaluateAll(groups => groups.map(group => group.dataset.year)), ['1', '2', '3'], 'The basket is grouped by start year');
  await edit('126449');
  await sheet.getByRole('combobox', { name: 'Start year for Satinique Smooth Moisture Shampoo, 280ml', exact: true }).selectOption('4');
  await done();
  assert.equal(await page.locator('.rs-plan-year[data-year="4"] .rs-story-product').count(), 1, 'A rescheduled product moves to its start year');
  await period('5 years').check();
  assert.equal(await page.locator('.rs-result [data-year]').count(), 5);
  await customMonths(12);
  assert.equal(await page.locator('.rs-revenue').innerText(), 'RM 118.00', 'Future products cannot change year-one revenue');
  assert.equal(await page.locator('.rs-plan-year[data-later]').count(), 3, 'Products after the period are flagged');
  await page.locator('#rs-customers').fill('100');
  assert.equal(await page.locator('#rs-customers').getAttribute('aria-invalid'), 'true');
  await page.locator('#rs-customers').blur();
  assert.equal(await page.locator('#rs-customers').inputValue(), '20');
  await page.getByRole('button', { name: 'Decrease starting customers', exact: true }).click();
  assert.equal(await page.locator('#rs-customers').inputValue(), '19');
  await page.locator('#rs-customers').fill('1');
  await page.locator('#rs-customers').blur();
  await page.getByRole('button', { name: 'Decrease new customers a year', exact: true }).click();
  assert.equal(await page.locator('#rs-customers-per-year').inputValue(), '0');
  assert.match(await page.locator('#rs-growth-help').innerText(), /Growth is off/);
  await page.getByRole('button', { name: 'Increase new customers a year', exact: true }).click();
  await page.locator('.rs-retention > summary').click();
  await page.getByRole('radio', { name: 'Annual attrition', exact: true }).check();
  await page.getByRole('spinbutton', { name: 'Annual customer retention percent', exact: true }).fill('50');
  await page.locator('#rs-months').fill('13');
  assert.equal(await page.locator('.rs-result [data-year]').count(), 2, 'A 13-month plan has a partial second year');
  await page.getByRole('button', { name: 'Running total', exact: true }).click();
  await page.locator('.rs-chart').waitFor();
  const ticks = await page.locator('.rs-chart > text').allTextContents();
  assert.ok(ticks.includes('Today') && ticks.includes('13m'), `Short plans keep month ticks: ${ticks}`);
  await page.getByRole('checkbox', { name: 'By category', exact: true }).check();
  assert.ok(await page.locator('.rs-chart [data-category]').count());
  await page.locator('.rs-year-revenue > summary').click();
  assert.equal(await page.locator('.rs-year-revenue tbody tr').count(), 2);
  assert.match(await page.locator('.rs-year-revenue tbody tr').last().innerText(), /2 \(1 mo\)/);
  await page.getByRole('button', { name: 'Clear basket', exact: true }).click();
  assert.equal(await page.locator('.rs-revenue').innerText(), 'RM 0.00');
  await reset();
  assert.equal(await page.locator('.rs-story-product').count(), 1);
  assert.equal(await page.locator('.rs-story-amount').innerText(), 'RM 118.00');
}
